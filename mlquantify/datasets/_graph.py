"""Graph quantification datasets (Planetoid citation networks)."""
import os
from ._base import get_data_home, fetch_remote, finish_xy

_BASE = "https://github.com/kimiyoung/planetoid/raw/master/data/"
_EXTS = ["x","y","tx","ty","allx","ally","graph","test.index"]


def fetch_planetoid_cora_citeseer_pubmed(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, name="cora"):
    """Planetoid citation graphs: Cora / CiteSeer / PubMed (graph nodes).

    The three standard Planetoid citation networks selected with ``name``. Nodes are papers with bag-of-words/TF-IDF features and a topic label; ``.graph`` holds the adjacency (citation links). Cora: 2708 nodes, 1433 features, 7 classes. CiteSeer: 3327 / 3703 / 6. PubMed: 19717 / 500 / 3.

    Quantification: node-level quantification under covariate/structural graph shift.

    ======================   ================
    Nodes                    2708 / 3327 / 19717
    Features                 1433 / 3703 / 500 (sparse)
    Classes                  7 / 6 / 3
    ======================   ================

    Source: https://github.com/kimiyoung/planetoid

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    name : {'cora', 'citeseer', 'pubmed'}, default='cora'
        Which citation network to load.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Yang, Z. et al. (2016). Revisiting semi-supervised learning with graph embeddings. ICML 2016.
    Sen, P. et al. (2008). Collective classification in network data. AI Magazine.

    Examples
    --------
    >>> b = fetch_planetoid_cora_citeseer_pubmed(name='cora'); b.data.shape
    >>> # (2708, 1433)  sparse; b.graph has the edges
    """
    import numpy as np, pickle, scipy.sparse as sp
    d = get_data_home(data_home); nd = os.path.join(d, "planetoid", name)
    for e in _EXTS:
        fetch_remote(_BASE + "ind.%s.%s" % (name, e), os.path.join(nd, "ind.%s.%s" % (name, e)), download_if_missing, n_retries, delay)
    o = {}
    for e in ["x","y","tx","ty","allx","ally","graph"]:
        with open(os.path.join(nd, "ind.%s.%s" % (name, e)), "rb") as f: o[e] = pickle.load(f, encoding="latin1")
    ti = np.loadtxt(os.path.join(nd, "ind.%s.test.index" % name), dtype=int)
    feat = sp.vstack((o["allx"], o["tx"])).tolil(); lab = np.vstack((o["ally"], o["ty"]))
    order = np.sort(ti); feat[ti, :] = feat[order, :]; lab[ti, :] = lab[order, :]
    return finish_xy(feat.tocsr(), lab.argmax(1), return_X_y, protocol, n_samples, sample_size, random_state, "planetoid-%s" % name, "GitHub kimiyoung/planetoid", graph=o["graph"])
