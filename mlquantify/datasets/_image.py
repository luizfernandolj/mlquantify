"""Image quantification datasets (parsed to numpy)."""
import os
from ._base import get_data_home, fetch_remote, finish_xy


def fetch_mnist_usps(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, domain="mnist", subset="train"):
    """MNIST -> USPS handwritten digits (image, covariate shift).

    Two digit-image datasets selected with ``domain``. *mnist*: 70000 28x28 grayscale images (60000 train / 10000 test) flattened to 784 features. *usps*: 9298 16x16 images (7291 train / 2007 test) flattened to 256 features. Both are 10-class; train on one domain, quantify the other for covariate shift.

    Quantification: a digit covariate-shift pair (train on MNIST, quantify on USPS).

    ======================   ================
    Samples                  70000 (MNIST) / 9298 (USPS)
    Features                 784 (MNIST) / 256 (USPS)
    Classes                  10
    ======================   ================

    Source: https://ossci-datasets.s3.amazonaws.com/mnist/  +  LIBSVM usps

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    domain : {'mnist', 'usps'}, default='mnist'
        Which domain to return.
    subset : {'train', 'test', 'all'}, default='train'
        Which split to return.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    LeCun, Y. et al. (1998); Hull, J. (1994).

    Examples
    --------
    >>> b = fetch_mnist_usps(domain='usps', subset='test'); b.data.shape  # doctest: +SKIP
    (2007, 256)
    """
    import numpy as np, gzip, struct, bz2
    d = get_data_home(data_home); root = os.path.join(d, "mnist_usps")
    def rd_idx(p):
        with gzip.open(p, "rb") as f: raw = f.read()
        m = struct.unpack(">I", raw[:4])[0]
        if m == 2051:
            n, r, c = struct.unpack(">III", raw[4:16]); return np.frombuffer(raw[16:], np.uint8).reshape(n, r * c)
        return np.frombuffer(raw[8:], np.uint8)
    def mnist():
        base = "https://ossci-datasets.s3.amazonaws.com/mnist/"
        fn = {"Xtr":"train-images-idx3-ubyte.gz","ytr":"train-labels-idx1-ubyte.gz","Xte":"t10k-images-idx3-ubyte.gz","yte":"t10k-labels-idx1-ubyte.gz"}
        return {k: rd_idx(fetch_remote(base + v, os.path.join(root, v), download_if_missing, n_retries, delay)) for k, v in fn.items()}
    def rd_libsvm(p, nf=256):
        X, y = [], []
        with bz2.open(p, "rt") as f:
            for line in f:
                t = line.split(); y.append(int(float(t[0])) - 1); row = np.zeros(nf, np.float32)
                for it in t[1:]:
                    i, v = it.split(":"); row[int(i) - 1] = float(v)
                X.append(row)
        return np.asarray(X), np.asarray(y)
    def usps():
        b = "https://www.csie.ntu.edu.tw/~cjlin/libsvmtools/datasets/multiclass/"
        Xtr, ytr = rd_libsvm(fetch_remote(b + "usps.bz2", os.path.join(root, "usps.bz2"), download_if_missing, n_retries, delay))
        Xte, yte = rd_libsvm(fetch_remote(b + "usps.t.bz2", os.path.join(root, "usps.t.bz2"), download_if_missing, n_retries, delay))
        return {"Xtr": Xtr, "ytr": ytr, "Xte": Xte, "yte": yte}
    D = mnist() if domain == "mnist" else usps()
    if subset == "train": X, y = D["Xtr"], D["ytr"]
    elif subset == "test": X, y = D["Xte"], D["yte"]
    else: X = np.concatenate([D["Xtr"], D["Xte"]]); y = np.concatenate([D["ytr"], D["yte"]])
    return finish_xy(X, y, return_X_y, protocol, n_samples, sample_size, random_state, "%s-%s" % (domain, subset), "MNIST(S3)/USPS(LIBSVM)")


def fetch_cifar10(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, subset="train"):
    """CIFAR-10 natural images (image, 10-class, balanced).

    60000 32x32 colour images (50000 train / 10000 test) in 10 object classes (airplane, automobile, bird, cat, ...), flattened to 3072 uint8 features. Perfectly class-balanced; commonly used for label/prior-shift quantification.

    Quantification: standard image label-shift quantification (Alexandari-style).

    ======================   ================
    Samples                  60000 (50000 / 10000)
    Features                 3072 (32x32x3 uint8)
    Classes                  10 (balanced)
    ======================   ================

    Source: https://www.cs.toronto.edu/~kriz/cifar.html

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    subset : {'train', 'test', 'all'}, default='train'
        Which split to return.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Krizhevsky, A. (2009). Learning multiple layers of features from tiny images.

    Examples
    --------
    >>> b = fetch_cifar10(subset='test'); b.data.shape  # doctest: +SKIP
    (10000, 3072)
    """
    import numpy as np, tarfile, pickle
    d = get_data_home(data_home); root = os.path.join(d, "cifar10")
    tgz = fetch_remote("https://www.cs.toronto.edu/~kriz/cifar-10-python.tar.gz", os.path.join(root, "cifar-10-python.tar.gz"), download_if_missing, n_retries, delay)
    base = os.path.join(root, "cifar-10-batches-py")
    if not os.path.isdir(base):
        with tarfile.open(tgz) as t: t.extractall(root)
    def load(f):
        with open(f, "rb") as fh: dd = pickle.load(fh, encoding="bytes")
        return dd[b"data"], np.asarray(dd[b"labels"])
    Xtr = ytr = None
    if subset in ("train", "all"):
        Xs, ys = [], []
        for i in range(1, 6):
            X, y = load(os.path.join(base, "data_batch_%d" % i)); Xs.append(X); ys.append(y)
        Xtr = np.concatenate(Xs); ytr = np.concatenate(ys)
    if subset == "train": X, y = Xtr, ytr
    elif subset == "test": X, y = load(os.path.join(base, "test_batch"))
    else:
        Xte, yte = load(os.path.join(base, "test_batch")); X = np.concatenate([Xtr, Xte]); y = np.concatenate([ytr, yte])
    return finish_xy(X, y, return_X_y, protocol, n_samples, sample_size, random_state, "cifar10-%s" % subset, "Toronto")
