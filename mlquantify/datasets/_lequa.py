"""LeQua 2024 competition datasets (official Zenodo record 11661820)."""
import os
from ._base import get_data_home, fetch_remote, finish_xy, Bunch

_BASE = "https://zenodo.org/records/11661820/files/%s?download=1"
_TASKS = {"T1": "binary, prior-prob shift", "T2": "multiclass-28, prior-prob shift", "T3": "ordinal, prior-prob shift", "T4": "binary, covariate shift"}


def fetch_lequa2024(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, task="T1", include_test=False):
    """LeQua 2024 competition vectors, all tasks via ``task`` (text/ordinal).

    Official LeQua 2024 data (Zenodo 11661820): 256-dimensional document vectors with controlled prevalence/covariate shift. ``task='T1'`` binary (prior-prob shift), ``'T2'`` 28-class, ``'T3'`` ordinal, ``'T4'`` binary covariate shift. Returns the training set as ``(X, y)``; ``.data_dir`` points at the extracted dev sample files for official-protocol evaluation.

    Quantification: the field's official shared task -- directly comparable, citable results.

    ======================   ================
    Features                 256 (document vectors)
    Classes                  2 (T1/T4) / 28 (T2) / ordinal (T3)
    Shift                    prior-prob (T1-T3) / covariate (T4)
    ======================   ================

    Source: https://lequa2024.github.io/  (Zenodo 11661820)

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    task : {'T1', 'T2', 'T3', 'T4'}, default='T1'
        Which LeQua-2024 task to load.
    include_test : bool, default=False
        Also download the large official test bag zip.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Esuli, A., Moreo, A. & Sebastiani, F. (2024). LeQua 2024 overview. CLEF 2024.

    Examples
    --------
    >>> b = fetch_lequa2024(task='T3'); b.data.shape[1]
    >>> # 256
    """
    task = str(task).upper()
    if task not in _TASKS:
        raise ValueError("task must be one of %s (got %r)" % (sorted(_TASKS), task))
    import zipfile, pandas as pd
    d = get_data_home(data_home); root = os.path.join(d, "lequa2024", task)
    files = ["%s.train_dev.zip" % task, "%s.test_prevalences.zip" % task]
    if include_test: files.append("%s.test.zip" % task)
    for nm in files:
        z = fetch_remote(_BASE % nm, os.path.join(root, nm), download_if_missing, n_retries, delay)
        with zipfile.ZipFile(z) as zf: zf.extractall(root)
    train = None
    for dp, _, fs in os.walk(root):
        if "training_data.txt" in fs: train = os.path.join(dp, "training_data.txt"); break
    if train is None:
        return Bunch(data_dir=root, DESCR="LeQua 2024 %s extracted; training_data.txt not found" % task)
    df = pd.read_csv(train)
    y = df.iloc[:, 0].to_numpy(); X = df.iloc[:, 1:].to_numpy()
    return finish_xy(X, y, return_X_y, protocol, n_samples, sample_size, random_state, "lequa2024-%s" % task, "Zenodo 11661820", data_dir=root)
