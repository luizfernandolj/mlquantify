"""Synthetic / generated quantification streams."""
from ._base import finish_xy


def fetch_sea_concepts(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, n=50000, drift=True, noise=0.1):
    """SEA Concepts: synthetic stream with abrupt concept drift (binary).

    A pure-Python generator of the SEA stream (Street & Kim, 2001). Three features are drawn uniformly in [0, 10]; only the first two decide the label via ``f1 + f2 <= theta`` (the third is irrelevant). With ``drift=True`` the threshold ``theta`` changes across four equal blocks (8, 9, 7, 9.5), and ``noise`` flips a fraction of labels.

    Quantification: controllable concept drift to isolate concept-shift behaviour.

    ======================   ================
    Samples                  n (default 50000)
    Features                 3 (real; 1 irrelevant)
    Classes                  2
    Drift                    4 concepts (abrupt)
    ======================   ================

    Source: generated in pure Python (no download)

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    n : int, default=50000
        Number of instances to generate.
    drift : bool, default=True
        If True, cycle through four concepts (thresholds 8/9/7/9.5).
    noise : float, default=0.1
        Fraction of labels randomly flipped.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Street, W. & Kim, Y. (2001). A streaming ensemble algorithm (SEA). KDD 2001.

    Examples
    --------
    >>> b = fetch_sea_concepts(n=10000, drift=True); b.data.shape
    (10000, 3)
    """
    import numpy as np
    rng = np.random.default_rng(random_state); thr = np.array([8.0, 9.0, 7.0, 9.5])
    F = rng.uniform(0, 10, size=(n, 3)).astype(np.float32)
    blk = (np.minimum(3, np.arange(n) * 4 // n) if drift else np.zeros(n, int))
    y = ((F[:, 0] + F[:, 1]) <= thr[blk]).astype(int)
    flip = rng.random(n) < noise; y[flip] = 1 - y[flip]
    return finish_xy(F, y, return_X_y, protocol, n_samples, sample_size, random_state, "sea_concepts", "synthetic (Street & Kim 2001)", feature_names=["f1","f2","f3"])
