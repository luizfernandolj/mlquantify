def fetch_newsgroups20(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, subset="train"):
    """20 Newsgroups: Usenet posts in 20 topics (text, multiclass).

    Roughly 18800 Usenet messages partitioned by date into a train split (11314 docs) and a test split (7532 docs), across 20 topics (politics, sci.*, comp.*, rec.*, religion, ...). Returned as raw text + integer category labels; vectorise with your own pipeline.

    Quantification: fills the multiclass-text gap; classic, trivially obtainable.

    ======================   ================
    Documents                11314 train / 7532 test
    Features                 raw text
    Classes                  20 (~balanced)
    ======================   ================

    Source: https://ndownloader.figshare.com/files/5975967 (20news-bydate.tar.gz)

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    subset : {'train', 'test'}, default='train'
        Which bydate split to load.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Lang, K. (1995). NewsWeeder. ICML 1995.

    Examples
    --------
    >>> b = fetch_newsgroups20(subset='train'); len(b.data), len(b.target_names)  # doctest: +SKIP
    (11314, 20)
    """
    import tarfile
    d = get_data_home(data_home); root = os.path.join(d, "newsgroups20")
    tgz = fetch_remote("https://ndownloader.figshare.com/files/5975967", os.path.join(root, "20news-bydate.tar.gz"), download_if_missing, n_retries, delay)
    sub = {"train": "20news-bydate-train", "test": "20news-bydate-test"}[subset]; base = os.path.join(root, sub)
    if not os.path.isdir(base):
        with tarfile.open(tgz) as t: t.extractall(root)
    cats = sorted(os.listdir(base)); texts, labels = [], []
    for ci, cat in enumerate(cats):
        cd = os.path.join(base, cat)
        for fn in os.listdir(cd):
            with open(os.path.join(cd, fn), encoding="latin-1") as fh: texts.append(fh.read())
            labels.append(ci)
    return finish_xy(texts, labels, return_X_y, protocol, n_samples, sample_size, random_state, "20newsgroups", "figshare", target_names=cats)


def fetch_imdb(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, subset="train"):
    """IMDB Large Movie Review sentiment (text, binary, balanced).

    50000 polar movie reviews split evenly into 25000 train and 25000 test, each split balanced between positive and negative. Long, free-text documents; returned as raw text + 0/1 labels.

    Quantification: the binary sentiment workhorse for text quantification.

    ======================   ================
    Documents                25000 per split
    Features                 raw text
    Classes                  2 (balanced)
    ======================   ================

    Source: https://ai.stanford.edu/~amaas/data/sentiment/

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    subset : {'train', 'test'}, default='train'
        Which split to load.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Maas, A. et al. (2011). Learning word vectors for sentiment analysis. ACL 2011.

    Examples
    --------
    >>> b = fetch_imdb(subset='test'); len(b.data)  # doctest: +SKIP
    25000
    """
    import tarfile
    d = get_data_home(data_home); root = os.path.join(d, "imdb")
    tgz = fetch_remote("https://ai.stanford.edu/~amaas/data/sentiment/aclImdb_v1.tar.gz", os.path.join(root, "aclImdb_v1.tar.gz"), download_if_missing, n_retries, delay)
    base = os.path.join(root, "aclImdb", subset)
    if not os.path.isdir(base):
        with tarfile.open(tgz) as t: t.extractall(root)
    texts, labels = [], []
    for lab, nm in [(0, "neg"), (1, "pos")]:
        cd = os.path.join(base, nm)
        for fn in os.listdir(cd):
            with open(os.path.join(cd, fn), encoding="utf-8") as fh: texts.append(fh.read())
            labels.append(lab)
    return finish_xy(texts, labels, return_X_y, protocol, n_samples, sample_size, random_state, "imdb", "Stanford (Maas et al. 2011)")


def fetch_multidomain_sentiment(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, domain="books"):
    """Multi-Domain (Blitzer) Amazon review sentiment (text, covariate shift).

    Amazon product reviews in four domains -- books, dvd, electronics, kitchen -- selected with ``domain``. Each domain has 2000 labelled reviews (1000 positive, 1000 negative) in the processed bag-of-words 'processed_acl' format. Training on one domain and quantifying another is the canonical covariate/domain-shift setup.

    Quantification: cross-domain train/test -> the standard covariate-shift text testbed.

    ======================   ================
    Documents                2000 per domain
    Features                 bag-of-words text
    Classes                  2 (balanced)
    Domains                  books / dvd / electronics / kitchen
    ======================   ================

    Source: https://www.cs.jhu.edu/~mdredze/datasets/sentiment/

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.
    domain : {'books','dvd','electronics','kitchen'}, default='books'
        Which product domain to load.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Blitzer, J. et al. (2007). Domain adaptation for sentiment classification. ACL 2007.

    Examples
    --------
    >>> b = fetch_multidomain_sentiment(domain='dvd'); len(b.data)  # doctest: +SKIP
    2000
    """
    import tarfile
    d = get_data_home(data_home); root = os.path.join(d, "multidomain_sentiment")
    tgz = fetch_remote("https://www.cs.jhu.edu/~mdredze/datasets/sentiment/processed_acl.tar.gz", os.path.join(root, "processed_acl.tar.gz"), download_if_missing, n_retries, delay)
    base = os.path.join(root, "processed_acl", domain)
    if not os.path.isdir(base):
        with tarfile.open(tgz) as t: t.extractall(root)
    texts, labels = [], []
    for lab, fn in [(1, "positive.review"), (0, "negative.review")]:
        with open(os.path.join(base, fn), encoding="latin-1") as fh:
            for line in fh:
                line = line.strip()
                if line: texts.append(line); labels.append(lab)
    return finish_xy(texts, labels, return_X_y, protocol, n_samples, sample_size, random_state, "multidomain-%s" % domain, "Blitzer et al. 2007")


def fetch_sentiment140(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None):
    """Sentiment140: 1.6M timestamped tweets (text, binary, temporal).

    1.6 million tweets weakly labelled by emoticons as negative (0) or positive (1), in original chronological order (the ``date`` field is exposed in the Bunch). Returned as raw tweet text + 0/1 labels; ideal for estimating the sentiment-trend curve over time.

    Quantification: a real timeline for quantification-over-time of sentiment.

    ======================   ================
    Documents                1600000
    Features                 raw text (+ date)
    Classes                  2 (balanced 0/4)
    Order                    chronological
    ======================   ================

    Source: https://www.kaggle.com/datasets/kazanova/sentiment140 (Stanford mirror)

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Go, A., Bhayani, R. & Huang, L. (2009). Twitter sentiment classification. Stanford.

    Examples
    --------
    >>> b = fetch_sentiment140(); len(b.data)  # doctest: +SKIP
    1600000
    """
    import zipfile, pandas as pd
    d = get_data_home(data_home)
    z = fetch_remote("http://cs.stanford.edu/people/alecmgo/trainingandtestdata.zip", os.path.join(d, "sentiment140", "data.zip"), download_if_missing, n_retries, delay)
    with zipfile.ZipFile(z) as zf:
        nm = [n for n in zf.namelist() if "training" in n.lower()][0]
        with zf.open(nm) as fh:
            df = pd.read_csv(fh, encoding="latin-1", header=None, names=["target","ids","date","flag","user","text"])
    y = (df["target"].to_numpy() == 4).astype(int)
    return finish_xy(df["text"].tolist(), y, return_X_y, protocol, n_samples, sample_size, random_state, "sentiment140", "Stanford (Go et al. 2009)", date=df["date"].tolist())


def fetch_rcv1_v2(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None):
    """RCV1-v2: Reuters news topics (text, sparse TF-IDF, multilabel).

    804414 Reuters news stories represented as 47236-dimensional cosine-normalised TF-IDF vectors, annotated with 103 hierarchical topic labels (multi-label). Uses scikit-learn's loader when available; otherwise downloads the raw token/label source files.

    Quantification: standard high-dimensional text-quant corpus; multilabel -- pick a topic column before a protocol.

    ======================   ================
    Documents                804414
    Features                 47236 (sparse TF-IDF)
    Classes                  103 topics (multilabel)
    ======================   ================

    Source: https://scikit-learn.org/stable/modules/generated/sklearn.datasets.fetch_rcv1.html

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Lewis, D. et al. (2004). RCV1: A new benchmark collection. JMLR 5.

    Examples
    --------
    >>> b = fetch_rcv1_v2(); b.data.shape  # doctest: +SKIP
    (804414, 47236)  sparse
    """
    d = get_data_home(data_home)
    try:
        from sklearn.datasets import fetch_rcv1
        ds = fetch_rcv1(data_home=os.path.join(d, "rcv1_v2"))
        if return_X_y: return ds.data, ds.target
        return Bunch(data=ds.data, target=ds.target, sample_id=ds.sample_id, target_names=list(ds.target_names),
                     DESCR="RCV1-v2 (multilabel). Pick a topic column before using a protocol=.")
    except Exception as e:
        files = {"lyrl2004_tokens_test_pt0.dat.gz": "https://ndownloader.figshare.com/files/5976069",
                 "lyrl2004_tokens_test_pt1.dat.gz": "https://ndownloader.figshare.com/files/5976066",
                 "lyrl2004_tokens_test_pt2.dat.gz": "https://ndownloader.figshare.com/files/5976063",
                 "lyrl2004_tokens_test_pt3.dat.gz": "https://ndownloader.figshare.com/files/5976060",
                 "lyrl2004_tokens_train.dat.gz": "https://ndownloader.figshare.com/files/5976057",
                 "rcv1v2.topics.qrels.gz": "https://ndownloader.figshare.com/files/5976048"}
        for nm, u in files.items(): fetch_remote(u, os.path.join(d, "rcv1_v2", nm), download_if_missing, n_retries, delay)
        return Bunch(data_dir=os.path.join(d, "rcv1_v2"), DESCR="raw RCV1 figshare token/label files")
