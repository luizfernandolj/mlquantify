def fetch_mushroom(*, data_home=None, download_if_missing=True, return_X_y=False, as_frame=False, n_retries=3, delay=1.0, protocol=None, n_samples=1000, sample_size=500, random_state=None, target_col=None):
    """Mushroom: edible vs. poisonous (binary, all-categorical).

    Each of 8124 gilled mushrooms (Agaricus/Lepiota) is described by 22 nominal attributes (cap shape/colour, odour, gill size, spore-print colour, habitat, ...). The task is to tell edible from poisonous; odour alone makes it almost linearly separable.

    Quantification: an easy, near-balanced sanity check -- good quantifiers should be near-perfect.

    ======================   ================
    Samples                  8124
    Features                 22 (categorical)
    Classes                  2 (edible 51.8% / poisonous 48.2%)
    Missing                  2480 (stalk-root '?')
    ======================   ================

    Source: https://archive.ics.uci.edu/dataset/73/mushroom

    Parameters
    ----------
    data_home : str or path-like, default=None
        Folder used to cache the downloaded file(s); defaults to ``_data/`` next to the package.
    download_if_missing : bool, default=True
        If False, raise instead of downloading when the cache is empty.
    return_X_y : bool, default=False
        Return ``(X, y)`` instead of a Bunch.
    as_frame : bool, default=False
        Return ``.data`` as a DataFrame, ``.target`` as a Series, and a combined ``.frame``
        (features + a ``"target"`` column).
    n_retries : int, default=3
        Number of download attempts before giving up.
    delay : float, default=1.0
        Seconds to wait between attempts.
    protocol : {None, "app", "npp", "upp", "ppp"} or mlquantify protocol, default=None
        If set, draw evaluation sample-bags with an mlquantify protocol; the Bunch then also has
        ``.samples`` (index bags into ``.data``), ``.prevalences`` and ``.protocol``.
    n_samples : int, default=1000
        Number of prevalence points (bags) generated by the protocol.
    sample_size : int, default=500
        Instances per bag (the protocol ``batch_size``).
    random_state : int or None, default=None
        Seed forwarded to the protocol.

    Returns
    -------
    data : Bunch
        Dictionary-like object. Attributes: ``data`` (features), ``target`` (labels),
        ``feature_names``, ``target_names``, ``DESCR``; ``frame`` when ``as_frame=True``; and
        ``samples`` / ``prevalences`` / ``protocol`` when ``protocol`` is set.
    (X, y) : tuple
        Returned instead when ``return_X_y=True``.

    References
    ----------
    Schlimmer, J. (1987). Mushroom records, UCI ML Repository (#73).

    Examples
    --------
    >>> from mlquantify.datasets import fetch_mushroom
    >>> b = fetch_mushroom()  # doctest: +SKIP
    >>> b.data.shape  # doctest: +SKIP
    (8124, 22)
    """
    import pandas as pd
    d = get_data_home(data_home)
    csv = fetch_remote("https://archive.ics.uci.edu/static/public/73/data.csv", os.path.join(d, "mushroom", "data.csv"), download_if_missing, n_retries, delay)
    df = pd.read_csv(csv)
    tcol = target_col if target_col is not None else ("poisonous" if "poisonous" in df.columns else df.columns[-1])
    y = df[tcol]; X = df.drop(columns=[tcol])
    return finish_tabular(X, y, df, as_frame, return_X_y, protocol, n_samples, sample_size, random_state, "mushroom", "UCI #73")


